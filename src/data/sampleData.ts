// CAPACITY DATA
// ============================================
export const generateCapacityData = (): CapacityData[] => {
  const data: CapacityData[] = [];
  const today = new Date();

  users.filter(u => u.role !== 'admin').forEach(user => {
    for (let i = 0; i < 7; i++) {
      const date = new Date(today);
      date.setDate(date.getDate() + i);
      const dateStr = date.toISOString().split('T')[0];
      const dayOfWeek = date.getDay();

      // Skip weekends
      if (dayOfWeek === 0 || dayOfWeek === 6) {
        data.push({
          userId: user.id,
          date: dateStr,
          scheduledHours: 0,
          availableHours: 0,
          utilizationPercent: 0,
          tasks: [],
        });
        continue;
      }

      // Random utilization for demo
      const scheduled = Math.floor(Math.random() * 10) + 2;
      data.push({
        userId: user.id,
        date: dateStr,
        scheduledHours: scheduled,
        availableHours: 8,
        utilizationPercent: (scheduled / 8) * 100,
        tasks: [],
      });
    }
  });

  return data;
};

